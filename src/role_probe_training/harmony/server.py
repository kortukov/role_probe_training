"""OpenAI-compatible chat server that renders with Harmony and samples by token IDs.

Clients (Inspect) send ordinary chat-completions requests. For every request the
server renders the conversation with `render_turns`, replaying each earlier assistant
turn from the completion tokens it generated, asks the sampler for completion token IDs
of the prompt, parses the completion, and records prompt and completion tokens with
their message spans. Two modes share the code:

* per-episode routes `/episodes/<id>/v1/...` for on-policy training, where an episode
  registers its seed first and its requests are strictly sequential;
* a plain `/v1/chat/completions` route for evaluation runs, where earlier turns are
  identified by the tool-call IDs the server itself issued or, for turns without calls,
  by the messages the client sent before them and their text.

Every prompt is checked to extend the previous prompt of its conversation exactly.
"""
from contextlib import contextmanager
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import re
import threading
import time
import traceback
import urllib.error
import urllib.request

from role_probe_training.trajectories.inspect_export import conversation_key, prefix_keys
from .parse import completion_to_chat, walk_completion
from .records import request_record
from .render import RenderConfig, completion_prompt, render_turns, tokens

ROUTE = re.compile(r'(?:/episodes/([^/]+))?/v1/(chat/completions|models)')


class Server(ThreadingHTTPServer):
    request_queue_size = 128
    daemon_threads = True


class VllmSampler:
    """Sample completion token IDs from a vLLM completions endpoint."""

    def __init__(self, base_url, model, timeout=1800, temperature=1.0):
        self.base_url = base_url.rstrip('/')
        self.model = model
        self.timeout = timeout
        self.temperature = float(temperature)

    def __call__(self, prompt, budget, stops, seed):
        body = dict(model=self.model, prompt=prompt, max_tokens=budget, temperature=self.temperature, top_p=1., top_k=-1,
                    seed=seed, stop_token_ids=list(stops), return_token_ids=True, skip_special_tokens=False)
        request = urllib.request.Request(self.base_url + '/v1/completions', data=json.dumps(body).encode(),
                                         headers={'Content-Type': 'application/json'})
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                result = json.load(response)
        except urllib.error.HTTPError as error:
            raise RuntimeError(error.read().decode()) from error
        choice = result['choices'][0]
        if not choice.get('token_ids') or choice.get('prompt_token_ids') != prompt:
            raise ValueError('Exact generation token IDs missing or changed')
        return choice['token_ids']


class ContextExhausted(Exception):
    """The conversation already ended at the context limit; carries the stopped entry."""


def chat_to_turns(messages, retained):
    """Convert an OpenAI-style history into renderer turns.

    Earlier assistant turns are taken from `retained`, the completion tokens this server
    generated. A turn with tool calls is keyed by the tuple of call IDs the server issued;
    a text-only turn by ('text', key of the messages before it, its text), which tells
    apart conversations that start with the same instructions and first user message. An
    assistant turn the server did not generate cannot be rendered and is rejected. A turn
    the server refused for lack of context (`completion_ids` None) means the conversation
    has ended.
    """
    turns, names, prefixes = [], {}, prefix_keys(messages)
    for index, message in enumerate(messages):
        role = message['role']
        if role in ('system', 'developer', 'user'):
            turns.append({'role': role, 'content': message.get('content') or ''})
        elif role == 'assistant':
            ids = tuple(call['id'] for call in message.get('tool_calls') or [])
            text = message.get('content')
            if isinstance(text, list):
                text = ''.join(part.get('text', '') for part in text if part.get('type', 'text') == 'text')
            retained_key = ids if ids else ('text', prefixes[index], (text or '').strip())
            if retained_key not in retained:
                raise ValueError(f'Assistant turn {index} has no retained generation tokens; '
                                 'only turns generated by this server can be replayed')
            entry = retained[retained_key]
            if entry['completion_ids'] is None:
                raise ContextExhausted(entry)
            for call in message.get('tool_calls') or []:
                names[call['id']] = call['function']['name']
            turns.append({'role': 'assistant', 'tokens': entry['completion_ids'], 'call_ids': ids,
                          'retained_key': retained_key})
        elif role == 'tool':
            call_id = message.get('tool_call_id')
            if call_id not in names:
                raise ValueError(f'Tool message {index} answers unknown call {call_id!r}')
            turns.append({'role': 'tool', 'name': names[call_id], 'content': message.get('content') or ''})
        else:
            raise ValueError(f'Unsupported message role {role!r}')
    return turns


class HarmonyChatServer:
    """See module docstring. `sampler(prompt_ids, budget, stops, seed) -> completion_ids`."""

    def __init__(self, output, sampler, *, config, context_limit, max_tokens, model_name,
                 policy_step=None, require_episodes=False, temperature=1.0):
        self.output = Path(output)
        self.output.mkdir(parents=True, exist_ok=True)
        self.sampler = sampler
        self.config = config
        self.context_limit = context_limit
        self.max_tokens = max_tokens
        self.temperature = float(temperature)
        self.model_name = model_name
        self.policy_step = policy_step
        self.require_episodes = require_episodes
        self.state = {'episodes': {}, 'errors': [], 'retained': {}, 'counter': 0}
        self.lock = threading.Lock()
        self.control = tokens()
        self.stops = self.control.stop

    def append(self, name, row):
        with self.lock:
            with (self.output / name).open('a') as stream:
                stream.write(json.dumps(row) + '\n')

    def register(self, episode_id, seed):
        with self.lock:
            if episode_id in self.state['episodes']:
                raise ValueError(f'Episode {episode_id} is already registered')
            self.state['episodes'][episode_id] = dict(seed=int(seed), request=0, retained={},
                                                      lock=threading.Lock())

    def models(self):
        return {'object': 'list', 'data': [{'id': self.model_name, 'object': 'model', 'created': 0,
                                            'owned_by': 'local', 'max_model_len': self.context_limit}]}

    def validate(self, body, episode):
        if body.get('stream'):
            raise ValueError('Streaming is not supported')
        if body.get('temperature', self.temperature) != self.temperature or body.get('top_p', 1) != 1:
            raise ValueError(f'Sampling must use temperature={self.temperature:g}, top_p=1')
        effort = body.get('reasoning_effort')
        if effort is not None and effort != self.config.reasoning_effort:
            raise ValueError(f'Client reasoning_effort {effort!r} differs from the server {self.config.reasoning_effort!r}')
        requested = body.get('max_tokens') or body.get('max_completion_tokens')
        if requested is not None and int(requested) != self.max_tokens:
            raise ValueError(f'Client max_tokens {requested} differs from the server {self.max_tokens}')
        if episode is not None and int(body.get('seed', -1)) != episode['seed']:
            raise ValueError('Request seed does not match the episode route')

    def context_stop(self, key, index, prompt_tokens, model, prefix):
        """An episode boundary, not a generation or a server error: the client ends its loop."""
        self.append('episode_stops.jsonl', dict(episode_id=key, policy_step=self.policy_step,
            reason='serving_context_limit', prompt_tokens=prompt_tokens, context_limit=self.context_limit,
            generated_tokens=0, generation_index=index, prefix_key=prefix))
        return {'id': f'{key}_context_limit', 'object': 'chat.completion', 'created': int(time.time()),
                'model': model,
                'choices': [{'index': 0, 'message': {'role': 'assistant', 'content': ''}, 'finish_reason': 'stop'}],
                'usage': {'prompt_tokens': prompt_tokens, 'completion_tokens': 0, 'total_tokens': prompt_tokens}}

    def complete(self, episode_id, episode, body):
        """One generation. Sequential within an episode or conversation."""
        self.validate(body, episode)
        key = episode_id if episode is not None else conversation_key(body['messages'])
        prefix = prefix_keys(body['messages'])[-1]
        retained = episode['retained'] if episode is not None else self.state['retained']
        model = body.get('model', self.model_name)
        try:
            turns = chat_to_turns(body['messages'], retained)
        except ContextExhausted as stopped:
            # A client that keeps talking after the stop (a user simulator) gets the same stop again.
            index = sum(message['role'] == 'assistant' for message in body['messages'])
            return self.context_stop(key, index, len(stopped.args[0]['prompt_ids']), model, prefix)
        tools = body.get('tools') or []
        prompt_rendering = render_turns(turns, self.config, tools=tools)
        prompt = completion_prompt(prompt_rendering)
        assistant_turns = [turn for turn in turns if turn['role'] == 'assistant']
        index = len(assistant_turns)
        if assistant_turns:
            before = retained[assistant_turns[-1]['retained_key']]
            expected = before['prompt_ids'] + before['completion_ids']
            if expected[-1] == self.control.ret:
                expected[-1] = self.control.end  # a replayed final answer ends with <|end|>
            if prompt[:len(expected)] != expected:
                raise ValueError('Prompt does not extend the previous prompt of this conversation exactly')
        seed = (episode['seed'] if episode is not None else int(body.get('seed', 0))) + index * 1000003
        budget = min(self.max_tokens, self.context_limit - len(prompt))
        if budget <= 0:
            retained[('text', prefix, '')] = dict(prompt_ids=prompt, completion_ids=None, content='')
            return self.context_stop(key, index, len(prompt), model, prefix)
        # Record the exact failing input even if generation fails before a completion exists.
        self.append('inputs.jsonl', dict(episode_id=key, generation_index=index, policy_step=self.policy_step,
                                         seed=seed, prompt_ids=prompt))
        started = time.perf_counter()
        completion = list(self.sampler(prompt, budget, self.stops, seed))
        seconds = time.perf_counter() - started
        entries, error = walk_completion(completion)
        parsed = completion_to_chat(entries, tools, error)
        message = parsed['message']
        with self.lock:
            self.state['counter'] += 1
            number = self.state['counter']
        for position, call in enumerate(message.get('tool_calls', [])):
            call['id'] = (f'{key}_{index + 1}_{position}' if episode is not None
                          else f'call_{number:08d}_{position}')
        call_ids = tuple(call['id'] for call in message.get('tool_calls', []))
        record = request_record(prompt_rendering, completion, self.config, episode_id=key,
                                policy_step=self.policy_step, generation_index=index, seed=seed,
                                temperature=self.temperature, seconds=seconds, call_ids=list(call_ids),
                                previous_call_ids=list(assistant_turns[-1]['call_ids']) if assistant_turns else [],
                                invalid=parsed['invalid'], issues=parsed['issues'], completion_source=len(body['messages']),
                                prefix_key=prefix, content=message.get('content') or '')
        # Persist raw samples before answering; malformed outputs stay auditable.
        self.append('requests.jsonl', record)
        self.append('parser_events.jsonl', dict(episode_id=key, generation_index=index, policy_step=self.policy_step,
                                                invalid=parsed['invalid'], issues=parsed['issues']))
        retained[call_ids if call_ids else ('text', prefix, (message.get('content') or '').strip())] = dict(
            prompt_ids=prompt, completion_ids=completion, content=message.get('content') or '')
        if episode is not None:
            episode['request'] += 1
        capped = completion[-1] not in self.stops
        reason = 'stop' if parsed['invalid'] else ('length' if capped else ('tool_calls' if call_ids else 'stop'))
        return {'id': f'{key}_{index + 1}', 'object': 'chat.completion', 'created': int(time.time()),
                'model': model,
                'choices': [{'index': 0, 'message': message, 'finish_reason': reason}],
                'usage': {'prompt_tokens': len(prompt), 'completion_tokens': len(completion),
                          'total_tokens': len(prompt) + len(completion)}}

    def handler(self):
        server = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def reply(self, status, value):
                encoded = json.dumps(value).encode()
                self.send_response(status)
                self.send_header('Content-Type', 'application/json')
                self.send_header('Content-Length', str(len(encoded)))
                self.end_headers()
                self.wfile.write(encoded)

            def do_GET(self):
                route = ROUTE.fullmatch(self.path)
                if route and route[2] == 'models':
                    return self.reply(200, server.models())
                self.reply(404, {'error': 'Unknown route'})

            def do_POST(self):
                try:
                    body = json.loads(self.rfile.read(int(self.headers['Content-Length'])))
                    if self.path == '/episode':
                        server.register(body['id'], body['seed'])
                        return self.reply(200, {'ok': True})
                    route = ROUTE.fullmatch(self.path)
                    if route is None or route[2] != 'chat/completions':
                        raise ValueError('Unknown route')
                    episode_id = route[1]
                    if episode_id is None and server.require_episodes:
                        raise ValueError('This server requires per-episode routes')
                    episode = server.state['episodes'].get(episode_id) if episode_id else None
                    if episode_id and episode is None:
                        raise ValueError('Unregistered episode')
                    if server.state['errors']:
                        return self.reply(409, {'error': {'message': 'Serving stopped after an earlier failure',
                                                          'type': 'harmony_serving_error'}})
                    if episode is not None:
                        with episode['lock']:
                            return self.reply(200, server.complete(episode_id, episode, body))
                    return self.reply(200, server.complete(None, None, body))
                except (BrokenPipeError, ConnectionResetError):
                    # The client gave up waiting (its own time limit or timeout). The generation is
                    # already recorded; nothing is wrong with the server, so serving continues.
                    server.append('client_disconnects.jsonl', dict(path=self.path, time=time.time()))
                except Exception:
                    with server.lock:
                        server.state['errors'].append(traceback.format_exc())
                        (server.output / 'server_errors.json').write_text(json.dumps(server.state['errors'], indent=2))
                    self.reply(500, {'error': {'message': server.state['errors'][-1].splitlines()[-1],
                                               'type': 'harmony_serving_error'}})
        return Handler

    @contextmanager
    def serving(self, host='127.0.0.1', port=0):
        server = Server((host, port), self.handler())
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            yield f'http://{host}:{server.server_port}'
        finally:
            server.shutdown()
            thread.join()
            server.server_close()
