"""Tables and loss plots for the header-role probe fits; reads metrics/fits/*.json.

Writes metrics/tables.md (fit summary, fit attempts, fitter agreement, per-role accuracy),
APPENDIX.md (confusion tables of every layer, fitter and split), metrics/summary.json and
plots/*.png.
README.md and RUNNING.md are authored separately and are never overwritten.
"""
import argparse
import json
from pathlib import Path

UPSTREAM_RATE = 1e-3
SHORT = {'system': 'sys', 'developer': 'dev', 'user': 'user', 'analysis': 'ana', 'commentary': 'com', 'final': 'fin',
         'tool_call': 'call', 'tool_output': 'out', 'analysis_tool_call': 'a-call', 'analysis_tool_output': 'a-out'}
# Chart colors and chrome: the reference palette of the dataviz guidance. Blue and orange are
# training and validation everywhere; learning rates take other hues.
TRAIN, VALIDATION, MUTED = '#2a78d6', '#eb6834', '#898781'
RATE_COLORS = ('#1baf7a', '#6250d6', '#e87ba4')
SURFACE, GRID, AXIS, INK, SECONDARY = '#fcfcfb', '#e1e0d9', '#c3c2b7', '#0b0b0b', '#52514e'


def pct(value):
    return 'n/a' if value is None else f'{100 * value:.1f}'


def rate_of(record):
    return record.get('learning_rate') or UPSTREAM_RATE


def variant_of(record):
    return record.get('variant', record['backend'])


def name_of(record):
    return f"cuML, tol {record['tol']:.0e}" if record['backend'] == 'cuml' else f'AdamW, rate {rate_of(record):g}'


def order(record):
    """cuML first, from the configured tolerance to tighter ones; then AdamW by learning rate."""
    return (0, -record['tol']) if record['backend'] == 'cuml' else (1, rate_of(record))


def load(folder):
    """Fits keyed by (layer, variant), in the order of `order`."""
    records = [json.loads(path.read_text()) for path in sorted(folder.glob('layer_*_*.json'))]
    records.sort(key=lambda r: (r['layer'], *order(r)))
    return {(r['layer'], variant_of(r)): r for r in records}


def variants_of(fits):
    return list(dict.fromkeys(variant for _, variant in sorted(fits, key=lambda key: order(fits[key]))))


def effort(record):
    """What the fitter ran: solver iterations (cuML) or optimizer steps (AdamW) of the kept fit."""
    if record['backend'] == 'cuml':
        return f"{record['iterations']:,} iterations (stopped by {record['termination']})"
    return f"{record['runs'][-1]['steps']:,} steps"


def summary_rows(fits):
    rows = []
    for (layer, variant), r in fits.items():
        rows.append({'layer': layer, 'fitter': variant, 'name': name_of(r), 'converged': r['converged'], 'effort': effort(r),
                     'train_loss': r['train']['nll'], 'validation_loss': r['validation']['nll'],
                     'train_accuracy': r['train']['accuracy'], 'validation_accuracy': r['validation']['accuracy'],
                     'train_balanced_accuracy': r['train']['balanced_accuracy'],
                     'validation_balanced_accuracy': r['validation']['balanced_accuracy'],
                     'cuml_objective': r['objective_audit']['objective'],
                     'cuml_objective_max_abs_gradient': r['objective_audit']['max_abs_gradient'],
                     'train_tokens': r['train']['n_tokens'], 'validation_tokens': r['validation']['n_tokens']})
    return rows


def role_table(columns, roles):
    """Per-role accuracy: `columns` is a list of (heading, metrics of one probe on one split)."""
    lines = ['| Role | Tokens | ' + ' | '.join(heading for heading, _ in columns) + ' |', '|---|---:|' + '---:|' * len(columns)]
    for role in roles:
        lines.append(f"| `{role}` | {columns[0][1]['by_role'][role]['n_tokens']:,} | "
                     + ' | '.join(pct(m['by_role'][role]['accuracy']) for _, m in columns) + ' |')
    for name, key in (('**All tokens**', 'accuracy'), ('**Mean over roles**', 'balanced_accuracy')):
        lines.append(f"| {name} | {columns[0][1]['n_tokens']:,} | " + ' | '.join(pct(m[key]) for _, m in columns) + ' |')
    return lines


def tables(fits, rows, agreement):
    roles = next(iter(fits.values()))['roles']
    layers = sorted({layer for layer, _ in fits})
    lines = ['# Header-role probe fits: tables', '',
             'Generated by `src/experiments/gptoss_role_probes/header_roles/report.py` from `metrics/fits*/`.',
             'Loss is the mean cross-entropy per token in nats. Accuracy is in percent.', '',
             '## Fit summary', '',
             '"Test passed" is the convergence test of the fitter (README section 2): for cuML, that the solver stopped on',
             'its own gradient or loss-change test; for AdamW, the training-loss test, although the validation loss of the',
             'schedules in the next table shows that these fits still change.', '',
             '| Layer | Fitter | Test passed | Fit length | Train loss | Validation loss | Train accuracy | Validation accuracy | cuML objective | Largest gradient entry |',
             '|---:|---|---|---|---:|---:|---:|---:|---:|---:|']
    for row in rows:
        lines.append(f"| {row['layer']} | {row['name']} | {'yes' if row['converged'] else 'no'} | {row['effort']} | "
                     f"{row['train_loss']:.4f} | {row['validation_loss']:.4f} | {pct(row['train_accuracy'])} | "
                     f"{pct(row['validation_accuracy'])} | {row['cuml_objective']:.4f} | {row['cuml_objective_max_abs_gradient']:.1e} |")
    lines += ['', 'The last two columns evaluate the cuML objective (mean cross-entropy plus the L2 penalty) and its gradient at',
              'each solution, in double precision over all training tokens. They are reported only and decide nothing.',
              'The AdamW fitter minimises a different objective, so its gradient entry is not expected to be small.', '',
              '## Fit attempts', '',
              'cuML is fitted once per layer and tolerance. For AdamW, "change from previous" is the convergence test: the change of the',
              'final train loss from the schedule a quarter as long, relative to the later value (positive when the loss rose).', '',
              '| Layer | Fitter | Setting | Length | Final train loss | Final validation loss | Change from previous | Largest gradient entry | Stopped by | Passed | Seconds |',
              '|---:|---|---|---:|---:|---:|---:|---:|---|---|---:|']
    for (layer, _), r in fits.items():
        if r['backend'] == 'cuml':
            lines.append(f"| {layer} | cuML | tol {r['tol']:.0e} | {r['iterations']:,} | {r['train']['nll']:.6f} | "
                         f"{r['validation']['nll']:.6f} | | {r['objective_audit']['max_abs_gradient']:.1e} | {r['termination']} | "
                         f"{'yes' if r['converged'] else 'no'} | {r['seconds']:.0f} |")
        else:
            for previous, a in zip([None] + r['runs'], r['runs']):
                change = previous and (a['final_train_loss'] - previous['final_train_loss']) / a['final_train_loss']
                lines.append(f"| {layer} | {name_of(r)} | {a['steps']:,} steps | {a['optimizer_steps']:,} | {a['final_train_loss']:.6f} | "
                             f"{a['history'][-1]['validation_loss']:.6f} | "
                             f"{'' if change is None else f'{100 * change:+.2f}%'} | | schedule end | "
                             f"{'yes' if a['converged'] else 'no'} | {a['seconds']:.0f} |")
    if agreement:
        reference = name_of(fits[agreement[0]['layer'], agreement[0]['reference']])
        lines += ['', f'## Agreement with the probe of {reference}', '',
                  'Every other probe of a layer against its cuML probe of the tightest tolerance. On the validation tokens:',
                  'the share given the same role by both probes, and the mean total-variation distance between their',
                  'probability vectors (0 for equal probabilities, 1 for disjoint ones). Weight cosine compares the two',
                  'weight matrices after subtracting the mean over roles, which leaves the probabilities unchanged; the norm',
                  'ratio is the norm of the probe over the norm of the reference. Written by `fit.py compare`.', '',
                  '| Layer | Fitter | Test passed | Same predicted role | Total variation | Weight cosine | Weight norm ratio |',
                  '|---:|---|---|---:|---:|---:|---:|']
        present = [a for a in agreement if (a['layer'], a['variant']) in fits]
        for a in sorted(present, key=lambda a: (a['layer'], *order(fits[a['layer'], a['variant']]))):
            record = fits[a['layer'], a['variant']]
            if record is not None:
                lines.append(f"| {a['layer']} | {name_of(record)} | {'yes' if record['converged'] else 'no'} | "
                             f"{pct(a['same_prediction'])} | {a['mean_total_variation']:.3f} | {a['weight_cosine']:.3f} | "
                             f"{a['weight_norm_ratio']:.2f} |")
    for layer in layers:
        present = [r for (l, _), r in fits.items() if l == layer]
        for split in ('train', 'validation'):
            lines += ['', f'## Per-role accuracy, layer {layer}, {split}', '',
                      'Share of the tokens of each true role that the probe assigns to that role (recall).', '']
            lines += role_table([(name_of(r), r[split]) for r in present], roles)
    return '\n'.join(lines) + '\n'


def confusion_table(counts, roles):
    lines = ['| True \\ predicted | ' + ' | '.join(SHORT[r] for r in roles) + ' | Tokens |', '|---|' + '---:|' * (len(roles) + 1)]
    for role, row in zip(roles, counts):
        total = sum(row)
        lines.append(f'| `{role}` | ' + ' | '.join(f'{100 * value / total:.1f}' if total else 'n/a' for value in row) + f' | {total:,} |')
    return lines


def appendix(fits):
    roles = next(iter(fits.values()))['roles']
    lines = ['# Appendix: confusion tables', '',
             'Rows are true roles and columns are predicted roles, as percentages of each true role\'s tokens, so every row',
             'sums to 100 and the diagonal is the per-role accuracy. Train is the 225 fitting passages, validation the 25',
             'held-out passages; every passage appears once under each role. Generated by `report.py`.', '',
             'Column names: ' + ', '.join(f'{SHORT[r]} = `{r}`' for r in roles) + '.']
    for (layer, variant), r in fits.items():
        for split in ('train', 'validation'):
            lines += ['', f'<a id="layer-{layer}-{variant}-{split}"></a>', f'## Layer {layer}, {name_of(r)}, {split}', '',
                      f"Accuracy {pct(r[split]['accuracy'])}% over {r[split]['n_tokens']:,} tokens.", '']
            lines += confusion_table(r[split]['confusion_counts'], roles)
    return '\n'.join(lines) + '\n'


def style(ax, title, xlabel, ylabel, log_y=True):
    from matplotlib.ticker import FuncFormatter, LogLocator, NullFormatter
    ax.set_xscale('log')
    ax.set_facecolor(SURFACE)
    ax.grid(True, which='major', color=GRID, linewidth=1)
    ax.set_axisbelow(True)
    for side in ('top', 'right'):
        ax.spines[side].set_visible(False)
    for side in ('left', 'bottom'):
        ax.spines[side].set_color(AXIS)
    if log_y:
        # Plain numbers on the loss axis: a loss curve spans less than two decades.
        ax.set_yscale('log')
        ax.yaxis.set_major_locator(LogLocator(base=10, subs=(1, 2, 3, 5), numticks=12))
        ax.yaxis.set_major_formatter(FuncFormatter(lambda value, _: f'{value:g}'))
        ax.yaxis.set_minor_formatter(NullFormatter())
    ax.xaxis.set_major_formatter(FuncFormatter(lambda value, _: f'{value:,.0f}'))
    ax.tick_params(which='both', colors=SECONDARY, labelsize=9, length=3)
    ax.tick_params(which='minor', length=0)
    ax.set_xlabel(xlabel, color=SECONDARY); ax.set_ylabel(ylabel, color=SECONDARY)
    ax.set_title(title, color=INK, fontsize=11, loc='left')


def end_dot(ax, x, y, color):
    ax.plot([x], [y], marker='o', markersize=7, color=color, markeredgecolor=SURFACE, markeredgewidth=2, zorder=5)


def draw_cuml(ax, records, title):
    """Objective per L-BFGS iteration of every cuML tolerance; the solver logs nothing else per iteration.

    The runs follow nearly the same path, so they share one colour; a dot marks where each
    stopped and the text block names them.
    """
    notes = []
    for record in records:
        history = [h for h in record['history'] if h['iteration'] > 0]
        ax.plot([h['iteration'] for h in history], [h['objective'] for h in history], color=TRAIN, linewidth=2,
                solid_capstyle='round')
        end_dot(ax, history[-1]['iteration'], history[-1]['objective'], TRAIN)
        notes.append(f"tol {record['tol']:.0e}: {history[-1]['iteration']:,} iterations, final {history[-1]['objective']:.4f}")
    style(ax, title + ', training objective', 'L-BFGS iteration', 'Cross-entropy + L2 penalty (nats)')
    ax.text(0.97, 0.95, '\n'.join(notes), transform=ax.transAxes, ha='right', va='top', fontsize=9, color=INK, linespacing=1.5)


def draw_adamw(ax, record, title, reference=None):
    """Training and validation loss of the kept run; shorter schedules in grey for context;
    the cuML solution's losses as reference levels."""
    for run in record['runs'][:-1]:
        ax.plot([h['step'] for h in run['history']], [h['train_loss'] for h in run['history']], color=MUTED, linewidth=1,
                label='Training loss, shorter schedules' if run is record['runs'][0] else None)
    if reference is not None:
        for split, color in (('train', TRAIN), ('validation', VALIDATION)):
            ax.axhline(reference[split]['nll'], color=color, linewidth=1, linestyle=(0, (4, 3)),
                       label=f"cuML {'training' if split == 'train' else 'validation'} loss, {reference[split]['nll']:.4f}")
    kept = record['runs'][-1]['history']
    ax.plot([h['step'] for h in kept], [h['train_loss'] for h in kept], color=TRAIN, linewidth=2, solid_capstyle='round',
            label=f"Training loss, final {kept[-1]['train_loss']:.4f}")
    ax.plot([h['step'] for h in kept], [h['validation_loss'] for h in kept], color=VALIDATION, linewidth=2,
            solid_capstyle='round', label=f"Validation loss, final {kept[-1]['validation_loss']:.4f}")
    style(ax, title + ', loss', 'AdamW optimizer step', 'Cross-entropy (nats)')
    end_dot(ax, kept[-1]['step'], kept[-1]['validation_loss'], VALIDATION)
    end_dot(ax, kept[-1]['step'], kept[-1]['train_loss'], TRAIN)
    # Below the panel: at a high learning rate the curves fill every corner of it.
    ax.legend(frameon=False, fontsize=9, labelcolor=SECONDARY, loc='upper center', bbox_to_anchor=(0.5, -0.2), ncol=2)


def plots(fits, root, main_layer):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.ticker import FuncFormatter
    plt.rcParams['font.family'] = 'sans-serif'
    (root / 'plots').mkdir(exist_ok=True)
    layers = sorted({layer for layer, _ in fits})
    variants = variants_of(fits)
    adamw = [v for v in variants if not v.startswith('cuml')]

    def curves(selected, path):
        """One row per layer: the cuML objective (all tolerances in one panel), then one panel per AdamW
        learning rate fitted at all these layers."""
        shown = [v for v in adamw if all((layer, v) in fits for layer in selected)]
        fig, axes = plt.subplots(len(selected), 1 + len(shown), figsize=(5.6 * (1 + len(shown)), 4.6 * len(selected)),
                                 squeeze=False, facecolor=SURFACE)
        for row, layer in enumerate(selected):
            draw_cuml(axes[row][0], [fits[layer, v] for v in variants if v not in adamw and (layer, v) in fits],
                      f'Layer {layer}: cuML')
            shared = []
            for column, variant in enumerate(shown, start=1):
                ax, record = axes[row][column], fits[layer, variant]
                draw_adamw(ax, record, f'Layer {layer}: {name_of(record)}', fits.get((layer, 'cuml')))
                shared.append(ax)
            # The AdamW panels of a layer share one loss axis so that learning rates can be compared.
            if shared:
                low, high = min(ax.get_ylim()[0] for ax in shared), max(ax.get_ylim()[1] for ax in shared)
                for ax in shared:
                    ax.set_ylim(low, high)
        fig.tight_layout(h_pad=2.5, w_pad=2.5)
        fig.savefig(path, dpi=170, facecolor=SURFACE)
        plt.close(fig)

    def ladder(path):
        """Final loss against schedule length, training above validation: a converged fitter's line is flat at its right end."""
        splits = (('train', 'Final training loss (nats)', lambda run: run['final_train_loss']),
                  ('validation', 'Final validation loss (nats)', lambda run: run['history'][-1]['validation_loss']))
        fig, axes = plt.subplots(len(splits), len(layers), figsize=(3.5 * len(layers), 3.3 * len(splits)), squeeze=False,
                                 facecolor=SURFACE)
        for row, (split, ylabel, value) in enumerate(splits):
            for column, layer in enumerate(layers):
                ax = axes[row][column]
                reference = fits.get((layer, 'cuml'))
                if reference is not None:
                    ax.axhline(reference[split]['nll'], color=MUTED, linewidth=1, linestyle=(0, (4, 3)), label='cuML solution')
                for variant, color in zip(adamw, RATE_COLORS):
                    record = fits.get((layer, variant))
                    if record is None:
                        continue
                    ax.plot([run['steps'] for run in record['runs']], [value(run) for run in record['runs']], color=color,
                            linewidth=2, marker='o', markersize=6, markeredgecolor=SURFACE, markeredgewidth=1.5,
                            solid_capstyle='round', label=f'AdamW, rate {rate_of(record):g}')
                style(ax, f'Layer {layer}' if row == 0 else '', 'Schedule length (steps)' if row == len(splits) - 1 else '',
                      ylabel if column == 0 else '', log_y=False)
                ax.xaxis.set_major_formatter(FuncFormatter(lambda value, _: f'{value / 1e6:g}M' if value >= 1e6 else f'{value / 1e3:g}k'))
        # One legend for the figure: a learning rate may have been tried at some layers only.
        handles = {label: handle for ax in axes.ravel() for handle, label in zip(*ax.get_legend_handles_labels())}
        order = sorted(handles, key=lambda label: (label != 'cuML solution', label))
        fig.legend([handles[label] for label in order], order, frameon=False, fontsize=9, labelcolor=SECONDARY,
                   loc='upper center', ncol=len(order), bbox_to_anchor=(0.5, 1.0))
        fig.tight_layout(w_pad=1.5, h_pad=1.5, rect=(0, 0, 1, 0.95))
        fig.savefig(path, dpi=170, facecolor=SURFACE)
        plt.close(fig)

    if main_layer in layers:
        curves([main_layer], root / 'plots' / f'loss_curves_layer_{main_layer}.png')
    curves(layers, root / 'plots' / 'loss_curves.png')
    if adamw:
        ladder(root / 'plots' / 'adamw_final_loss.png')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('experiment_reports/gptoss_role_probes/header_roles'))
    parser.add_argument('--main-layer', type=int, default=12)
    args = parser.parse_args()
    fits = load(args.root / 'metrics' / 'fits')
    if not fits:
        raise SystemExit('No finished fits in metrics/fits')
    rows = summary_rows(fits)
    (args.root / 'metrics' / 'summary.json').write_text(json.dumps(rows, indent=1) + '\n')
    agreement = args.root / 'metrics' / 'fitter_agreement.json'
    agreement = json.loads(agreement.read_text()) if agreement.exists() else []
    (args.root / 'metrics' / 'tables.md').write_text(tables(fits, rows, agreement))
    (args.root / 'APPENDIX.md').write_text(appendix(fits))
    plots(fits, args.root, args.main_layer)
    print(f'Reported {len(fits)} fits')


if __name__ == '__main__':
    main()
